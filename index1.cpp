#include<iostream>
#include<bits/stdc++.h>
class Solution {
public:
    string originalDigits(string s) {
        unordered_map<char,int> mp;
        string ans="";
        for(int i=0;i<s.size();i++)
        {
            mp[s[i]]++;
        }
        bool found=false;
        do
        {
            if(mp.find('z')!=mp.end() && mp.find('e')!=mp.end() && mp.find('r')!=mp.end() && mp.find('o')!=mp.end())
            {
                ans+='0';
                mp['z']--;
                if(mp['z']==0)
                {
                    mp.erase('z');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                mp['r']--;
                if(mp['r']==0)
                {
                    mp.erase('r');
                }
                mp['o']--;
                if(mp['o']==0)
                {
                    mp.erase('o');
                }
                found=true;
            }
            if(mp.find('o')!=mp.end() && mp.find('n')!=mp.end() && mp.find('e')!=mp.end())
            {
                ans+='1';
                mp['o']--;
                if(mp['o']==0)
                {
                    mp.erase('o');
                }
                mp['n']--;
                if(mp['n']==0)
                {
                    mp.erase('n');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                found=true;
            }
            if(mp.find('t')!=mp.end() && mp.find('w')!=mp.end() && mp.find('o')!=mp.end())
            {
                ans+='2';
                mp['t']--;
                if(mp['t']==0)
                {
                    mp.erase('t');
                }
                mp['w']--;
                if(mp['w']==0)
                {
                    mp.erase('w');
                }
                mp['o']--;
                if(mp['o']==0)
                {
                    mp.erase('o');
                }
                found=true;
            }
            if(mp.find('t')!=mp.end() && mp.find('h')!=mp.end() && mp.find('r')!=mp.end() && mp.find('e')!=mp.end() && mp.find('e')!=mp.end() && mp['e']>=2)
            {
                ans+='3';
                mp['t']--;
                if(mp['t']==0)
                {
                    mp.erase('t');
                }
                mp['h']--;
                if(mp['h']==0)
                {
                    mp.erase('h');
                }
                mp['r']--;
                if(mp['r']==0)
                {
                    mp.erase('r');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                found=true;
            }
            if(mp.find('f')!=mp.end() && mp.find('o')!=mp.end() && mp.find('u')!=mp.end() && mp.find('r')!=mp.end())
            {
                ans+='4';
                mp['f']--;
                if(mp['f']==0)
                {
                    mp.erase('f');
                }
                mp['o']--;
                if(mp['o']==0)
                {
                    mp.erase('o');
                }
                mp['u']--;
                if(mp['u']==0)
                {
                    mp.erase('u');
                }
                mp['r']--;
                if(mp['r']==0)
                {
                    mp.erase('r');
                }
                found=true;
            }
            if(mp.find('f')!=mp.end() && mp.find('i')!=mp.end() && mp.find('v')!=mp.end() && mp.find('e')!=mp.end())
            {
                ans+='5';
                mp['f']--;
                if(mp['f']==0)
                {
                    mp.erase('f');
                }
                mp['i']--;
                if(mp['i']==0)
                {
                    mp.erase('i');
                }
                mp['v']--;
                if(mp['v']==0)
                {
                    mp.erase('v');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                found=true;
            }
            if(mp.find('s')!=mp.end() && mp.find('i')!=mp.end() && mp.find('x')!=mp.end())
            {
                ans+='6';
                mp['s']--;
                if(mp['s']==0)
                {
                    mp.erase('s');
                }
                mp['i']--;
                if(mp['i']==0)
                {
                    mp.erase('i');
                }
                mp['x']--;
                if(mp['x']==0)
                {
                    mp.erase('x');
                }
                found=true;
            }
            if(mp.find('s')!=mp.end() && mp.find('e')!=mp.end() && mp.find('v')!=mp.end() && mp.find('e')!=mp.end() && mp.find('n')!=mp.end() && mp['e']>=2)
            {
                ans+='7';
                mp['s']--;
                if(mp['s']==0)
                {
                    mp.erase('s');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                mp['v']--;
                if(mp['v']==0)
                {
                    mp.erase('v');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                mp['n']--;
                if(mp['n']==0)
                {
                    mp.erase('n');
                }
                found=true;
            }
            if(mp.find('e')!=mp.end() && mp.find('i')!=mp.end() && mp.find('g')!=mp.end() && mp.find('h')!=mp.end() && mp.find('t')!=mp.end())
            {
                ans+='8';
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                mp['i']--;
                if(mp['i']==0)
                {
                    mp.erase('i');
                }
                mp['g']--;
                if(mp['g']==0)
                {
                    mp.erase('g');
                }
                mp['h']--;
                if(mp['h']==0)
                {
                    mp.erase('h');
                }
                mp['t']--;
                if(mp['t']==0)
                {
                    mp.erase('t');
                }
                found=true;
            }
            if(mp.find('n')!=mp.end() && mp.find('i')!=mp.end() && mp.find('n')!=mp.end() && mp.find('e')!=mp.end() && mp['n']>=2)
            {
                ans+='9';
                mp['n']--;
                if(mp['n']==0)
                {
                    mp.erase('n');
                }
                mp['i']--;
                if(mp['i']==0)
                {
                    mp.erase('i');
                }
                mp['n']--;
                if(mp['n']==0)
                {
                    mp.erase('n');
                }
                mp['e']--;
                if(mp['e']==0)
                {
                    mp.erase('e');
                }
                found=true;
            }
        }while(mp.size()>0 && found==true);
        return ans;
    }
};